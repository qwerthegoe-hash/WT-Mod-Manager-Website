// Validate the handoff that future ChatGPT sessions use as a project map.
// This is a cheap CI consistency check: not a substitute for a source audit.
import {readFileSync, existsSync, statSync} from "node:fs";
import assert from "node:assert/strict";

const file="WTMM_FULL_PROJECT_HANDOFF_2026-11-19.txt";
assert.ok(existsSync(file),"Missing main handoff TXT");
const text=readFileSync(file,"utf8");
assert.ok(text.length>=45000,"The handoff must remain a comprehensive guide");
assert.ok(text.split("\n").length>900,"The handoff is unexpectedly truncated");
for(const name of [
  "src/main.py","ui/main_window.py","src/update_checker.py",
  "src/portable_updater.py","src/trust_center.py","src/crash_recovery.py",
  "docs/index.html","docs/trust.html",
  "supabase/functions/wtmm-mod-scan/index.ts",
  ".github/workflows/build-windows-exe.yml"
]) assert.ok(text.includes(name),"Missing critical source description: "+name);

const version=readFileSync("src/update_checker.py","utf8")
  .match(/^VERSION = "([^"]+)"$/m)?.[1];
assert.ok(version,"Cannot find app VERSION");
assert.ok(text.includes(version),"The handoff release snapshot is inconsistent with app version");

const entries=[...text.matchAll(/^FILE: (.+)$/gm)].map(x=>x[1].trim());
assert.ok(entries.length>=200,"The handoff file registry is incomplete");
assert.equal(entries.length,new Set(entries).size,"Duplicate file path in handoff");
for(const path of entries){
  assert.ok(!path.includes("..")&&!path.startsWith("/")&&!path.includes("\\"),
    "Unsafe or ambiguous relative path in registry");
  assert.ok(existsSync(path),"Documented file does not exist: "+path);
  assert.ok(statSync(path).isFile(),"Documented path is not a file: "+path);
  assert.ok(!path.includes("__pycache__")&&!path.endsWith(".pyc"),
    "Generated bytecode must never be listed as project source");
}

assert.ok(text.includes("UNSIGNED"),"Must describe unsigned release limitation");
assert.ok(text.includes("не автоматическая")||text.includes("НЕ гарантия"),
  "Must not represent ZIP structural checks as antivirus approval");
console.log("PASS: WTMM handoff verified; "+entries.length+" documented files, version "+version);
